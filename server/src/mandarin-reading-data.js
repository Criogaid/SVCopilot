export function isMandarinReadingCandidate(lyrics) {
  return typeof lyrics === "string" && MANDARIN_POLYPHONIC_CHARACTERS.has(lyrics);
}

export function lookupMandarinReading(phonemes) {
  if (typeof phonemes !== "string") return null;
  // 精确匹配用于暴露宿主格式漂移；未知格式必须由上层报告，不能静默猜测。
  return X_SAMPA_TO_TONELESS_PINYIN.get(phonemes) ?? null;
}
