import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_ROOT = new URL("https://resource.dreamtonics.com/scripting/");
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outputDir = path.resolve(scriptDir, "..", "api-docs", "official");
const concurrency = 4;

function hash(content) {
  return createHash("sha256").update(content).digest("hex");
}

function titleOf(html) {
  const match = html.match(/<title[^>]*>\s*([\s\S]*?)\s*<\/title>/i);
  return match ? match[1].replace(/\s+/g, " ").trim() : null;
}

function localPath(url) {
  let relative = decodeURIComponent(url.pathname.slice(SOURCE_ROOT.pathname.length));
  if (!relative || relative.endsWith("/")) relative += "index.html";
  const normalized = path.normalize(relative);
  if (normalized.startsWith("..") || path.isAbsolute(normalized)) {
    throw new Error(`Refusing to write outside the mirror: ${url}`);
  }
  return normalized;
}

function canonicalUrl(href, base = SOURCE_ROOT) {
  const url = new URL(href.replaceAll("&amp;", "&"), base);
  url.hash = "";
  url.search = "";
  if (url.href === new URL("index.html", SOURCE_ROOT).href) url.pathname = SOURCE_ROOT.pathname;
  return url;
}

function extractAttributeUrls(content, base) {
  const urls = [];
  const matcher = /(?:href|src)\s*=\s*["']([^"']+)["']/gi;
  for (const match of content.matchAll(matcher)) {
    try {
      urls.push(canonicalUrl(match[1], base));
    } catch {
      // 不完整或模板化链接与 API 镜像无关，跳过即可。
    }
  }
  return urls;
}

function isEnglishDocument(url) {
  if (url.origin !== SOURCE_ROOT.origin) return false;
  if (!url.pathname.startsWith(SOURCE_ROOT.pathname)) return false;
  if (url.pathname.startsWith(`${SOURCE_ROOT.pathname}ja/`)) return false;
  return url.pathname === SOURCE_ROOT.pathname || url.pathname.endsWith(".html");
}

function isLocalAsset(url) {
  if (url.origin !== SOURCE_ROOT.origin) return false;
  if (!url.pathname.startsWith(SOURCE_ROOT.pathname)) return false;
  return /\.(css|js|png|gif|jpe?g|svg|woff2?|ttf)$/i.test(url.pathname);
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      "User-Agent": "SV-Copilot API archive/1.0 (+local development use)",
      Accept: "text/html, text/css, application/javascript, */*;q=0.1",
    },
  });
  if (!response.ok) throw new Error(`GET ${url} failed: ${response.status} ${response.statusText}`);
  return Buffer.from(await response.arrayBuffer());
}

async function mapWithConcurrency(items, worker) {
  const results = [];
  let cursor = 0;
  const runners = Array.from({ length: Math.min(concurrency, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor++;
      results[index] = await worker(items[index]);
    }
  });
  await Promise.all(runners);
  return results;
}

async function save(url, content) {
  const relativePath = localPath(url);
  const destination = path.join(outputDir, relativePath);
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, content);
  return relativePath.replaceAll("\\", "/");
}

async function main() {
  await mkdir(outputDir, { recursive: true });
  console.log(`[sv-api] downloading index: ${SOURCE_ROOT}`);
  const indexContent = await fetchText(SOURCE_ROOT);
  const indexHtml = indexContent.toString("utf8");
  const pageUrls = [...new Map(
    [SOURCE_ROOT, ...extractAttributeUrls(indexHtml, SOURCE_ROOT)]
      .filter(isEnglishDocument)
      .map((url) => [url.href, url])
  ).values()];

  const pages = await mapWithConcurrency(pageUrls, async (url) => {
    const content = url.href === SOURCE_ROOT.href ? indexContent : await fetchText(url);
    const relativePath = await save(url, content);
    return {
      url: url.href,
      path: relativePath,
      title: titleOf(content.toString("utf8")),
      sha256: hash(content),
    };
  });

  const assetUrls = [...new Map(
    (await mapWithConcurrency(pages, async (page) => {
      const content = await fetchText(new URL(page.url));
      return extractAttributeUrls(content.toString("utf8"), new URL(page.url));
    }))
      .flat()
      .filter(isLocalAsset)
      .map((url) => [url.href, url])
  ).values()];
  const assets = await mapWithConcurrency(assetUrls, async (url) => {
    const content = await fetchText(url);
    return { url: url.href, path: await save(url, content), sha256: hash(content) };
  });

  const generatedAt = new Date().toISOString();
  const manifest = {
    schemaVersion: 1,
    source: SOURCE_ROOT.href,
    language: "en",
    generatedAt,
    documentationGeneratedAt:
      indexHtml
        .match(/Documentation generated by[\s\S]*?on\s+([\s\S]+?)\s+using\s+the /i)?.[1]
        ?.replace(/\s+/g, " ")
        .trim() ?? null,
    pages: pages.sort((a, b) => a.path.localeCompare(b.path)),
    assets: assets.sort((a, b) => a.path.localeCompare(b.path)),
  };
  await writeFile(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(
    path.join(outputDir, "README.md"),
    `# Dreamtonics 官方 Scripting Manual 镜像\n\n` +
      `- 来源：${SOURCE_ROOT.href}\n` +
      `- 语言：英文\n` +
      `- 抓取时间：${generatedAt}\n` +
      `- HTML 页：${pages.length}\n` +
      `- 静态资源：${assets.length}\n\n` +
      `原始版权和内容保留在各 HTML 文件中。请通过 \`manifest.json\` 追踪来源、版本和 SHA-256。` +
      `\n\n更新命令：\n\n\`npm run download:sv-api\`（在 \`server/\` 目录运行）。\n`
  );
  console.log(`[sv-api] saved ${pages.length} HTML pages and ${assets.length} assets to ${outputDir}`);
}

main().catch((error) => {
  console.error("[sv-api] download failed:", error);
  process.exitCode = 1;
});
